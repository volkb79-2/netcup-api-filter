#!/bin/bash
# netcup-api-filter finalize hook — runs via the mdt-shipped finalize_container_environment.py
# (post phase, after the generic mdt steps). This is netcup's project-SPECIFIC setup:
# Python venv, .env.workspace generation, SSH keys, aliases, development tools.
#
# Context env provided by finalize: MDT_WORKSPACE_DIR, MDT_DEVCONTAINER_DIR, MDT_ENV_TYPE,
# MDT_USER, MDT_UID, MDT_GID, MDT_DOCKER_GID.
set -euo pipefail

WS="${MDT_WORKSPACE_DIR:-$(pwd)}"
ENV_TYPE="${MDT_ENV_TYPE:-local}"
USER_NAME="${MDT_USER:-$(whoami)}"
USER_UID="${MDT_UID:-$(id -u)}"
USER_GID="${MDT_GID:-$(id -g)}"
DOCKER_GID="${MDT_DOCKER_GID:-$(getent group docker | cut -d: -f3 2>/dev/null || echo '118')}"

log() { echo "[netcup-setup] $*"; }

# ============================================================================
# 1. REPOSITORY PATHS & .env.workspace GENERATION
# ============================================================================
# netcup DOES use ciu (ciu.env + ciu.global.toml at the repo root); this hook
# writes .env.workspace as the shell-facing companion, and reads ciu.env where
# a value has an authoritative source there. An earlier revision of this file
# claimed "netcup doesn't use ciu" and dropped network setup on that basis --
# the claim was false and the drop broke pwmcp-based UI tests.
# REPO_ROOT is the container-visible path (the workspace); PHYSICAL_REPO_ROOT
# is the host path (needed for Docker bind mounts).

setup_repository_paths() {
    log "Setting up repository paths and .env.workspace..."

    export REPO_ROOT="$WS"

    # Detect PHYSICAL_REPO_ROOT: the host path for Docker bind mounts.
    # Priority 1: Manual override (for testing/debugging)
    # Priority 2: devcontainer.local_folder label (VS Code devcontainer)
    # Priority 3: Fallback to workspace dir (bare metal, SSH, CI/CD)
    local physical_repo_root
    if [[ -n "${PHYSICAL_REPO_ROOT:-}" ]]; then
        physical_repo_root="$PHYSICAL_REPO_ROOT"
        log "Using manual PHYSICAL_REPO_ROOT override: $physical_repo_root"
    else
        physical_repo_root=$(docker ps --format '{{.ID}} {{.Label "devcontainer.local_folder"}}' 2>/dev/null \
            | awk '$2 != "" { print $2; exit }' | head -1 || echo "$WS")
        if [[ "$physical_repo_root" == "$WS" ]]; then
            log "No devcontainer label found, using workspace dir: $physical_repo_root"
        else
            log "Detected via devcontainer.local_folder label: $physical_repo_root"
        fi
    fi

    export PHYSICAL_REPO_ROOT="$physical_repo_root"

    # Generate .env.workspace — shared workspace facts for shell workflows
    cat > "$WS/.env.workspace" << EOF
# ============================================================================
# Workspace Environment Configuration (Auto-generated)
# ============================================================================
# Generated by: .devcontainer/finalize.post.d/10-netcup-setup.sh
# Purpose: Provides workspace variables to scripts running outside finalize
#
# Sourced by: .vscode/ensure-mcp-connection.sh and documented manual workflows in tooling/*.
# run-gate and build_deployment.py receive their own declared environment; they do not read this file.
# Do not edit manually — regenerated on devcontainer rebuild.
# ============================================================================
export ENV_TYPE="$ENV_TYPE"
export USER_NAME="$USER_NAME"
export USER_UID="$USER_UID"
export USER_GID="$USER_GID"
export DOCKER_GID="$DOCKER_GID"
export REPO_ROOT="$REPO_ROOT"
export PHYSICAL_REPO_ROOT="$PHYSICAL_REPO_ROOT"
export DOCKER_UID="$USER_UID"
EOF

    log "Generated .env.workspace (REPO_ROOT=$REPO_ROOT, PHYSICAL_REPO_ROOT=$PHYSICAL_REPO_ROOT)"
}

# ============================================================================
# 2. PYTHON 3.11 VENV SETUP (CRITICAL FOR NETCUP)
# ============================================================================
# The base image provides modern Python (3.14) and uv. Production target is
# Python 3.11, so we pin the project venv to 3.11 via uv so that unit tests
# and the app run on the same interpreter as production.

setup_python_environment() {
    log "Setting up Python 3.11 project venv via uv..."

    # Prefer uv (ships in the base image); fail if not available
    if ! command -v uv &>/dev/null; then
        log "ERROR: uv not found (required for Python version pinning)"
        return 1
    fi

    log "uv version: $(uv --version 2>&1)"

    # Ensure CPython 3.11 is available (uv downloads it if needed)
    log "Ensuring Python 3.11 is available via uv..."
    if ! uv python install 3.11; then
        log "ERROR: uv python install 3.11 failed"
        return 1
    fi

    # Create (or refresh) the project venv at .venv/ pinned to 3.11
    log "Creating project venv at .venv/ (Python 3.11)..."
    if ! uv venv --python 3.11 .venv; then
        log "ERROR: uv venv --python 3.11 .venv failed"
        return 1
    fi

    # Install dev dependencies into the venv via uv pip
    local requirements_file="$WS/requirements-test.txt"
    if [[ ! -f "$requirements_file" ]]; then
        log "ERROR: requirements-test.txt not found at $requirements_file"
        return 1
    fi
    log "Installing dev dependencies from requirements-test.txt..."
    if ! uv pip install --python .venv/bin/python -r "$requirements_file"; then
        log "ERROR: uv pip install failed"
        return 1
    fi

    # UI tests requirements (optional — warn and continue if absent)
    local ui_req="$WS/ui_tests/requirements.txt"
    if [[ -f "$ui_req" ]]; then
        log "Installing ui_tests requirements..."
        if ! uv pip install --python .venv/bin/python -r "$ui_req"; then
            log "WARN: ui_tests/requirements.txt install failed (non-critical)"
        fi
    else
        log "ui_tests/requirements.txt not found — skipping (non-critical)"
    fi

    log "Project venv ready: $(.venv/bin/python --version 2>&1)"

    # ─── Add venv auto-activation to ~/.bashrc (REMOVE-AND-REWRITE, not add-if-absent)
    strip_bashrc_block "netcup-api-filter venv"
    # UNQUOTED heredoc: $WS expands HERE, at generation time, so the written
    # block contains this container's actual workspace path as a fact. A quoted
    # heredoc (<<'EOF') would emit the literal instead -- which is what the
    # first version of this block did, while carrying a comment claiming the
    # opposite. A hardcoded /workspaces/netcup-api-filter is exactly the
    # anti-pattern this migration exists to remove (AGENTS.md 4.2a).
    cat >> ~/.bashrc <<EOF

# >>> netcup-api-filter venv
# Auto-activate the project venv when entering a shell in the workspace.
# Path written at generation time from MDT_WORKSPACE_DIR -- not a default.
if [ -f "$WS/.venv/bin/activate" ]; then
    source "$WS/.venv/bin/activate"
fi
# <<< netcup-api-filter venv
EOF

    log "Added venv auto-activation to ~/.bashrc"
}

# ============================================================================
# 3. SSH KEYS AND ALIASES SETUP
# ============================================================================

setup_ssh_and_aliases() {
    log "Setting up SSH keys and bash aliases..."

    # ─── Strip old blocks, write fresh ones (REMOVE-AND-REWRITE) ──────────────

    strip_bashrc_block "Netcup Custom Aliases"
    cat >> ~/.bashrc <<'EOF'

# >>> Netcup Custom Aliases
# File viewing and navigation
alias ll='ls -l'
alias la='ls -la'
alias lt='tree -L 2'                    # tree: 2-level directory view
alias ltt='tree -L 3'                   # tree: 3-level directory view
alias cat='bat --paging=never'          # bat: syntax-highlighted cat
alias less='bat --paging=always'        # bat: pager mode

# Search and find
alias grep='rg'                         # ripgrep: fast grep
alias find='fd'                         # fd: fast find
alias fdf='fdfind'                      # fd-find: Debian package name

# Process management
alias ps='htop'                         # htop: interactive process viewer
alias psg='ps aux | grep -i'           # search processes

# Network tools
alias myip='curl -s ifconfig.me'        # get public IP
alias listening='netstat -tuln | grep LISTEN'  # show listening ports
alias ports='ss -tuln'                  # show all ports

# DNS queries
alias dig-short='dig +short'            # dig: short output only
alias dig-trace='dig +trace'            # dig: full DNS trace
alias nsl='nslookup'                    # nslookup: shorthand

# HTTP clients
alias curl-json='curl -H "Content-Type: application/json"'  # JSON curl
alias curl-time='curl -w "\n\nTime: %{time_total}s\n"'    # curl with timing
alias GET='http GET'                    # httpie: GET request
alias POST='http POST'                  # httpie: POST request

# Git shortcuts
alias gst='git status'                  # git: status
alias gd='git diff'                     # git: diff
alias glog='git log --oneline --graph --all --decorate'  # git: pretty log

# System info
alias diskspace='df -h'                 # disk usage
alias meminfo='free -h'                 # memory info
alias cpuinfo='lscpu'                   # CPU info

# Development tools
alias check='shellcheck'                # shellcheck: linter
alias json='jq .'                       # jq: pretty-print JSON
alias yaml='yq eval'                    # yq: YAML query
alias man='tldr'                        # tldr: simplified man pages

# File manager
alias fm='mc --nosubshell'              # Midnight Commander: no subshell

# SSH filesystem
alias mount-ssh='sshfs'                 # sshfs: shorthand
alias umount-ssh='fusermount -u'        # unmount sshfs
# <<< Netcup Custom Aliases
EOF

    log "Added/updated custom bash aliases"

    # ─── SSH setup (devcontainer only) ─────────────────────────────────────

    if [[ "$ENV_TYPE" != "devcontainer" ]]; then
        log "Skipping SSH key setup (not devcontainer environment)"
        return 0
    fi

    # SSH keys to add to agent (from mounted host ~/.ssh)
    local SSH_KEYS=("netcup-hosting218629-ed25519")
    local ssh_dir="/home/vscode/.ssh-host"

    if [[ ! -d "$ssh_dir" ]]; then
        log "Skipping SSH key setup (host SSH directory not mounted at $ssh_dir)"
        return 0
    fi

    log "Host SSH keys mounted at $ssh_dir"

    # Manage SSH agent (persistent across shell sessions)
    local ssh_agent_file="$HOME/.ssh-agent-info"

    if [[ -f "$ssh_agent_file" ]]; then
        # shellcheck source=/dev/null
        source "$ssh_agent_file" >/dev/null 2>&1 || true
        if kill -0 "${SSH_AGENT_PID:-0}" 2>/dev/null; then
            log "SSH agent already running (PID: $SSH_AGENT_PID)"
        else
            log "Stale SSH agent file found, starting new agent..."
            rm -f "$ssh_agent_file"
        fi
    fi

    if [[ -z "${SSH_AGENT_PID:-}" ]] || ! kill -0 "${SSH_AGENT_PID:-0}" 2>/dev/null; then
        log "Starting persistent SSH agent..."
        ssh-agent -s > "$ssh_agent_file"
        # shellcheck source=/dev/null
        source "$ssh_agent_file" >/dev/null 2>&1
    fi

    # ─── Add SSH agent sourcing to ~/.bashrc (REMOVE-AND-REWRITE) ────────────

    strip_bashrc_block "netcup SSH agent"
    cat >> ~/.bashrc <<'EOF'

# >>> netcup SSH agent
# Load SSH agent info for persistent agent across all shells
if [[ -f "$HOME/.ssh-agent-info" ]]; then
    # shellcheck source=/dev/null
    source "$HOME/.ssh-agent-info" >/dev/null 2>&1
fi
# <<< netcup SSH agent
EOF

    # ─── Add SSH keys to agent ──────────────────────────────────────────────

    for key in "${SSH_KEYS[@]}"; do
        if [[ -f "$ssh_dir/$key" ]]; then
            local key_fingerprint
            key_fingerprint=$(ssh-keygen -lf "$ssh_dir/$key" 2>/dev/null | awk '{print $2}')
            if ssh-add -l 2>/dev/null | grep -q "$key_fingerprint"; then
                log "SSH key $key already loaded"
            else
                log "Adding SSH key: $key"
                ssh-add "$ssh_dir/$key" 2>/dev/null \
                    && log "Added SSH key: $key" \
                    || log "WARN: Failed to add SSH key $key (passphrase required?)"
            fi
        else
            log "WARN: SSH key $key not found in $ssh_dir"
        fi
    done
}

# ============================================================================
# 4. DEVELOPMENT TOOLS CONFIGURATION
# ============================================================================

setup_development_tools() {
    log "Configuring development tools..."

    # Configure bat (cat replacement)
    if command -v bat &>/dev/null || command -v batcat &>/dev/null; then
        local bat_config_dir="$HOME/.config/bat"
        if [[ ! -d "$bat_config_dir" ]]; then
            mkdir -p "$bat_config_dir"
            cat > "$bat_config_dir/config" << 'EOF'
# Bat configuration (syntax-highlighted cat alternative)
--theme="Dracula"
--style="numbers,changes,header"
EOF
            log "Created bat configuration"
        fi
    fi

    # Configure Midnight Commander (mc)
    if command -v mc &>/dev/null; then
        mkdir -p "$HOME/.config/mc"
        log "Midnight Commander available"
    else
        log "Midnight Commander not available (non-critical)"
    fi

    log "Development tools configured"
}


# ============================================================================
# 5. DOCKER NETWORK CONNECTIVITY (pwmcp / sibling service containers)
# ============================================================================
# RESTORED 2026-08-06. The mdt migration dropped this on the stated basis that
# "netcup doesn't use pwmcp" -- false: UI tests reach Playwright-as-a-Service at
# ws://pwmcp-playwright:3000/, which only resolves once this devcontainer has
# JOINED the shared network. Without it those tests cannot connect at all.

setup_network_connectivity() {
    [ "${MDT_ENV_TYPE:-devcontainer}" = "devcontainer" ] || { log "not a devcontainer — skipping network setup"; return 0; }
    command -v docker >/dev/null 2>&1 || { log "WARN docker not available — skipping network setup"; return 0; }

    # NO default: the name is ciu-derived (<repo>-<path-hash>-network, see
    # ciu.env). A stale hardcoded fallback would silently put containers on a
    # DIFFERENT network than ciu renders -- split-brain, and invisible.
    local network_name="${DOCKER_NETWORK_INTERNAL:-}"
    if [ -z "$network_name" ] && [ -f "$WS/ciu.env" ]; then
        # shellcheck source=/dev/null
        network_name=$(. "$WS/ciu.env" >/dev/null 2>&1; printf '%s' "${DOCKER_NETWORK_INTERNAL:-}")
    fi
    if [ -z "$network_name" ]; then
        log "WARN DOCKER_NETWORK_INTERNAL not set and not found in ciu.env — skipping network join"
        log "WARN pwmcp-based UI tests will not be able to reach ws://pwmcp-playwright:3000/"
        return 0
    fi

    if ! docker network inspect "$network_name" >/dev/null 2>&1; then
        log "creating docker network: $network_name"
        docker network create "$network_name" >/dev/null 2>&1 || {
            log "WARN could not create network $network_name"; return 0; }
    fi

    local container_name
    container_name=$(docker ps --format '{{.Names}}' --filter volume="$WS" 2>/dev/null | head -1)
    if [ -z "$container_name" ]; then
        log "WARN could not detect this devcontainer's name — skipping network join"
    elif docker network inspect "$network_name" --format '{{range .Containers}}{{.Name}} {{end}}' 2>/dev/null | grep -qw "$container_name"; then
        log "already connected to $network_name"
        export DEVCONTAINER_NAME="$container_name"
    else
        log "connecting $container_name to $network_name"
        docker network connect "$network_name" "$container_name" >/dev/null 2>&1 \
            && export DEVCONTAINER_NAME="$container_name" \
            || log "WARN could not connect to $network_name — sibling containers unreachable by name"
    fi

    export DOCKER_NETWORK_INTERNAL="$network_name"
    cat >> "$WS/.env.workspace" <<EOF

# Docker network for reaching sibling service containers by name,
# e.g. ws://pwmcp-playwright:3000/ for UI tests.
export DOCKER_NETWORK_INTERNAL="$network_name"
export DEVCONTAINER_NAME="${DEVCONTAINER_NAME:-}"
EOF
}

# ============================================================================
# HELPER: Remove-and-rewrite ~/.bashrc blocks (NOT add-if-absent)
# ============================================================================
# Blocks are removed and rewritten rather than added-if-absent: the old
# add-if-absent guard meant any later correction never reached a container
# that had already been built once, so the source could look fixed while
# every existing container kept the defect. This is the "masked default"
# anti-pattern documented in AGENTS.md §4.2a.

strip_bashrc_block() {
    local name="$1"
    [ -f ~/.bashrc ] || return 0
    grep -q ">>> ${name}" ~/.bashrc 2>/dev/null || return 0
    sed -i "/^# >>> ${name}\$/,/^# <<< ${name}\$/d" ~/.bashrc
}

# ============================================================================
# MAIN EXECUTION
# ============================================================================

main() {
    log "Starting netcup-api-filter environment setup..."

    if ! setup_repository_paths; then
        log "ERROR: Repository path setup failed — cannot continue"
        return 1
    fi

    if ! setup_python_environment; then
        log "ERROR: Python environment setup failed — cannot continue"
        return 1
    fi

    if ! setup_ssh_and_aliases; then
        log "WARN: SSH and aliases setup had issues (non-critical)"
    fi

    if ! setup_development_tools; then
        log "WARN: Development tools setup had issues (non-critical)"
    fi

    if ! setup_network_connectivity; then
        log "WARN: Network connectivity setup had issues (pwmcp UI tests may fail)"
    fi

    log "finalize hook complete (REPO_ROOT=${REPO_ROOT:-?})"
}

main "$@"
